import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("../", import.meta.url));

test("CLI saves provenance, reproduces scores, renders SVG, and reports missing trials", (t) => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), "layout-cli-"));
  t.after(() => fs.rmSync(directory, { recursive: true, force: true }));
  const call = (...args) => spawnSync(process.execPath, [path.join(root, "experiments/cli.mjs"), ...args], { cwd: directory, env: { ...process.env, EXPERIMENT_RESULTS_DIR: directory }, encoding: "utf8" });
  const run = call("run", "--name=smoke", "--trials=2", "--nodes=30", "--variance=medium", "--aspects=1:4");
  assert.equal(run.status, 0, run.stderr);
  const file = path.join(directory, "runs/smoke.json");
  const payload = JSON.parse(fs.readFileSync(file));
  assert.equal(payload.provenance.node, process.version);
  assert.equal(payload.rows.length, 2);
  const verify = call("verify", "smoke", "--n=2");
  assert.equal(verify.status, 0, verify.stderr);
  assert.match(verify.stdout, /12件一致 \/ 0件不一致/);
  const svg = path.join(directory, "comparison.svg");
  assert.equal(call("compare", "smoke", "medium/1:4/0", `--out=${svg}`).status, 0);
  assert.match(fs.readFileSync(svg, "utf8"), /<svg/);
  payload.rows[0].scores.existing = null;
  payload.rows[0].errors.existing = "synthetic failure";
  fs.writeFileSync(file, JSON.stringify(payload));
  const summary = call("summary", "smoke");
  assert.match(summary.stdout, /INCOMPLETE/);
  assert.match(summary.stdout, /全手法成功 1\/2/);
  const top = call("top", "smoke").stdout;
  assert.match(top, /欠測のある 1 試行/);
  assert.match(top, /--- 対照例: \S+ が最良の試行/);
  assert.doesNotMatch(call("top", "smoke", "--contrast=0").stdout, /対照例/);
  assert.equal(call("verify", "smoke").status, 1);
  assert.equal(call("run", "--trials=0").status, 1);
  payload.config.metric = "time";
  payload.config.methods = ["existing", "budget-lpt"];
  payload.rows = [{ ...payload.rows[1], scores: { existing: 0.01, "budget-lpt": 0.03 }, errors: {} }];
  fs.writeFileSync(file, JSON.stringify(payload));
  assert.match(call("top", "smoke", "--by=baseline-wins").stdout, /margin=20.0ms/);
});
